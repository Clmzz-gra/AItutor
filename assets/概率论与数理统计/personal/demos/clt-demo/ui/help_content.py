HELP = r"""
### 中心极限定理（CLT）

**核心结论**：设 $X_1,\dots,X_n$ 独立同分布，总体均值 $\mu$、方差 $\sigma^2$。
则样本均值

$$\bar X=\frac{1}{n}\sum_{i=1}^n X_i$$

当 $n$ 足够大时近似服从正态分布：

$$\bar X \approx N\left(\mu,\ \frac{\sigma^2}{n}\right)$$

即：**无论总体分布是什么**（均匀、指数、二项……），样本均值的分布都会随
$n$ 增大而逼近钟形正态曲线。

**为什么重要？**

1. 它是统计推断（置信区间、假设检验）的理论基石——因为很多统计量都依赖样本均值。
2. 它解释了为什么"平均"能消除随机性：均值分布的方差 $\sigma^2/n$ 随 $n$ 缩小。

**演示要点**

- 直方图 = 从总体反复抽样算出的样本均值分布（**当前 n 的真实抽样结果**）。
- 红色曲线 = 理论正态 $N(\mu,\sigma^2/n)$（**解析真值**）。
- 两者都对应**当前 n**，语义一致；n 越大，直方图越贴合红色钟形。

### 参数含义

- **总体分布**：选择要演示的总体（均匀 / 指数 / 二项）。
- **样本量 n**：每组抽样的个数。n 越大，样本均值分布越接近正态。
- **抽样组数**：算多少个样本均值（直方图的样本量）。越多直方图越平滑。
- **随机种子**：固定后结果可复现。

### 操作步骤

1. 在左侧选择总体分布。
2. 拖动 n，观察直方图如何逼近红色正态钟形。
3. 点"自动演示"看 n 从 1 递增的逼近过程。
4. 查看"结果对比"面板的样本均值/标准差与理论真值对照。
"""


def render() -> None:
    import streamlit as st

    st.markdown(HELP)
